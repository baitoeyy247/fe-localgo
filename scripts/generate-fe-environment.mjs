import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const feRoot = path.resolve(__dirname, '..');
const outFile = path.join(feRoot, 'src/environments/environment.sit.ts');

function env(name, fallback = '') {
  const raw = process.env[name];
  const value = raw === undefined || raw === '' ? fallback : raw;
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const apiBaseUrl = env('NG_APP_API_BASE_URL', 'https://be-localgo.onrender.com/api');
const liffId = env('NG_APP_LIFF_ID', '2010177240-Bu98ZCLT');
const mapLat = env('NG_APP_MAP_DEFAULT_LAT', '13.7563');
const mapLng = env('NG_APP_MAP_DEFAULT_LNG', '100.5018');
const allowDevLogin =
  (process.env.NG_APP_ALLOW_DEV_LOGIN ?? 'false').toLowerCase() === 'true' ||
  (process.env.NG_APP_ALLOW_DEV_LOGIN ?? '') === '1';
const devLoginDisplayName = env('NG_APP_DEV_LOGIN_DISPLAY_NAME', 'ทดสอบ ผู้รับ 01');
// B-1: every deploy path (deploy-pages.sh / wrangler / CI) stamps the short commit.
function gitShortSha() {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: feRoot, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}
const rawSha = process.env.BUILD_COMMIT || process.env.NG_APP_BUILD_SHA || process.env.GITHUB_SHA || gitShortSha() || 'dev';
const buildSha = env('__unused__', rawSha.slice(0, 7));

const content = `// Generated by scripts/generate-fe-environment.mjs — do not edit by hand.
export const environment = {
  production: true,
  apiBaseUrl: '${apiBaseUrl}',
  liffId: '${liffId}',
  mapDefaultLat: ${mapLat},
  mapDefaultLng: ${mapLng},
  devLoginDisplayName: '${devLoginDisplayName}',
  allowDevLogin: ${allowDevLogin},
  privacyVersion: '1.0-mvp',
  buildSha: '${buildSha}',
  httpConsoleLog: true,
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content, 'utf8');
console.log(`Wrote ${path.relative(feRoot, outFile)}`);
console.log(`  apiBaseUrl: ${apiBaseUrl}`);
console.log(`  buildSha: ${buildSha}`);
